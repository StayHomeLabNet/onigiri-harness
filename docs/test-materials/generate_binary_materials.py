#!/usr/bin/env python3
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def write_minimal_pdf(path: Path) -> None:
    text = "Onigiri PDF Test Policy - The PDF access code is ORANGE-4821."
    stream = f"BT /F1 16 Tf 72 720 Td ({text}) Tj ET".encode("ascii")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    output = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for number, obj in enumerate(objects, 1):
        offsets.append(len(output))
        output.extend(f"{number} 0 obj\n".encode("ascii"))
        output.extend(obj)
        output.extend(b"\nendobj\n")
    xref = len(output)
    output.extend(f"xref\n0 {len(objects) + 1}\n".encode("ascii"))
    output.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        output.extend(f"{offset:010d} 00000 n \n".encode("ascii"))
    output.extend(
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode("ascii")
    )
    path.write_bytes(output)


def main() -> None:
    write_minimal_pdf(ROOT / "rag" / "06_pdf_policy.pdf")
    (ROOT / "negative" / "invalid-utf8.txt").write_bytes(
        b"Onigiri invalid UTF-8 fixture: \xff\xfe\xfa\x80"
    )
    print("Generated PDF and invalid UTF-8 fixtures.")


if __name__ == "__main__":
    main()
